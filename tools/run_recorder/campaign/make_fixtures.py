def edit_project(path, spec):
    con = sqlite3.connect(path)
    for rowid, meta in con.execute("select rowid, metadata_json from external_axis_groups").fetchall():
        m = json.loads(meta)
        abb = m.get("export_v1", {}).get("brands", {}).get("abb")
        if m.get("export_v1", {}).get("motion_role") == "extended_axis" and abb is not None                 and not spec.get("keep_station"):
            abb["station_frame_pose"] = VC_A_STN2
            abb.setdefault("station_frame_pose_urdf", MONARC_URDF_PLATE)
            con.execute("update external_axis_groups set metadata_json=? where rowid=?", (json.dumps(m), rowid))
    # The source of truth is the weld project's metadata; project_meta only mirrors it on save.
    for rowid, payload in con.execute("select rowid, payload_json from weld_projects").fetchall():
        p = json.loads(payload)
        p.setdefault("metadata", {})["work_zone"] = spec.get("work_zone", 0)
        con.execute("update weld_projects set payload_json=? where rowid=?", (json.dumps(p), rowid))
    con.execute("update project_meta set value=? where key='work_zone'", (str(spec.get("work_zone", 0)),))
    if spec.get("clear_touchups") or spec.get("touch_mm"):
        dx, dy, dz = spec.get("touch_mm", (0.0, 0.0, 0.0))
        con.execute("update weld_item_runtime_state set touch_offset_matrix_json=?",
                    (json.dumps([[1.0, 0, 0, dx], [0, 1.0, 0, dy], [0, 0, 1.0, dz], [0, 0, 0, 1.0]]),))
    for weld_id, name, payload in con.execute("select weld_id, name, payload_json from weld_items").fetchall():
        if name not in spec["welds"]:
            continue
        mode, preset = spec["welds"][name]
        p = json.loads(payload)
        p.setdefault("tool_path_parameters", {}).update(spec.get("tool_path", {}).get(name, {}))
        lib = p["weld_library"]
        if name in spec.get("weave", {}):
            lib.setdefault("weave_settings", {})["abb"] = dict(spec["weave"][name])
        if mode == "preset":
            lib["binding_mode"] = "snapshot"
            lib["parameters"] = dict(preset)
            lib["library_id"] = str(preset["id"])
            lib["display_name"] = preset["name"]
            for k in LEGACY_KEYS:
                lib.pop(k, None)
        else:
            lib["binding_mode"] = "manual"
        con.execute("update weld_items set payload_json=? where weld_id=?", (json.dumps(p), weld_id))
    con.commit()
    con.close()


def expected_params(lib):
    pre = lib.get("parameters", {})
    if lib.get("binding_mode") == "manual":
        m = lib["manual_parameters"]
        return {"udwp_flag": 1, "welder_type": WELDER_TYPE, "weld_proc": int(m["user_defined_proc"]),
                "travel_speed": float(m["user_defined_travel_speed"]),
                "wire_feed_speed": float(m["user_defined_wire_feed_speed"]),
                "arc_length": float(m["user_defined_arc_length"]), "arc_control": float(m["user_defined_arc_control"]),
                "weld_sched": int(pre["schedule_number"])}
    return {"udwp_flag": 0, "welder_type": WELDER_TYPE, "weld_proc": int(pre["procedure_number"]),
            "travel_speed": float(pre["travel_speed"]), "wire_feed_speed": float(pre["wire_feed_speed"]),
            "arc_length": 0.0, "arc_control": 0.0, "weld_sched": int(pre["schedule_number"])}


def _quat_to_matrix(w, x, y, z):
    return [[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
            [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
            [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]]


def _matrix_to_quat(m):
    tr = m[0][0] + m[1][1] + m[2][2]
    if tr > 0:
        s = math.sqrt(tr + 1.0) * 2
        q = [0.25 * s, (m[2][1] - m[1][2]) / s, (m[0][2] - m[2][0]) / s, (m[1][0] - m[0][1]) / s]
    elif m[0][0] > m[1][1] and m[0][0] > m[2][2]:
        s = math.sqrt(1.0 + m[0][0] - m[1][1] - m[2][2]) * 2
        q = [(m[2][1] - m[1][2]) / s, 0.25 * s, (m[0][1] + m[1][0]) / s, (m[0][2] + m[2][0]) / s]
    elif m[1][1] > m[2][2]:
        s = math.sqrt(1.0 + m[1][1] - m[0][0] - m[2][2]) * 2
        q = [(m[0][2] - m[2][0]) / s, (m[0][1] + m[1][0]) / s, 0.25 * s, (m[1][2] + m[2][1]) / s]
    else:
        s = math.sqrt(1.0 + m[2][2] - m[0][0] - m[1][1]) * 2
        q = [(m[1][0] - m[0][1]) / s, (m[0][2] + m[2][0]) / s, (m[1][2] + m[2][1]) / s, 0.25 * s]
    if q[0] < 0:
        q = [-v for v in q]
    return q


def base_weld_frame(index_transform, literal, touch=None):
    """The frame a base weld should be served with no localization correction: the module's
    nominal part pose (its wobjTG_Weld.oframe literal, at the reference index) moved by the
    planner's part transform at the weld's own positioner index (tool_path_parameters
    positioner_part_transform_base, a 4x4 in the robot base frame, meters), then by the weld's
    stored touch-up offset (weld_item_runtime_state.touch_offset_matrix_json, mm, base frame -
    the HMI's behaviour as measured on VC A, 2026-10-28)."""
    m = [[v * (1000.0 if j == 3 and i < 3 else 1.0) for j, v in enumerate(row)]
         for i, row in enumerate(index_transform)]                       # translation to mm
    if touch:
        m = [[sum(touch[i][k] * m[k][j] for k in range(4)) for j in range(4)] for i in range(4)]
    r_lit = _quat_to_matrix(*literal[3:])
    rot = [[sum(m[i][k] * r_lit[k][j] for k in range(3)) for j in range(3)] for i in range(3)]
    trans = [sum(m[i][k] * literal[k] for k in range(3)) + m[i][3] for i in range(3)]
    return [round(v, 3) for v in trans] + [round(v, 6) for v in _matrix_to_quat(rot)]


def main_module(con):
    rows = [r[0] for r in con.execute("select path from robot_bundle_files where path like 'ROBOT_PROGRAM/%.mod'")]
    current = [r for r in rows if r.count("/") == 1 and not re.search(r"_\d{8}_\d{6}\.mod$", r)]
    if len(current) != 1:
        raise RuntimeError("expected one main module, found %s" % current)
    return current[0], con.execute("select content_blob from robot_bundle_files where path=?",
                                   (current[0],)).fetchone()[0].decode("utf-8", "replace")


def write_expect(path, name, spec, out_dir):
    con = sqlite3.connect(pathlib.Path(path).as_uri() + "?mode=ro", uri=True)
    mod_path, text = main_module(con)
    lit = re.search(r"\bwobjTG_Weld\.oframe\s*:=\s*\[\[([^\]]*)\],\[([^\]]*)\]\]", text)
    literal = [float(v) for v in (lit.group(1) + "," + lit.group(2)).split(",")] if lit else None
    touch = {wid: json.loads(m) for wid, m in
             con.execute("select weld_id, touch_offset_matrix_json from weld_item_runtime_state") if m}
    welds = {}
    for wid, wname, payload in con.execute("select weld_id, name, payload_json from weld_items order by order_index"):
        p = json.loads(payload)
        pts = p.get("trimmed_extended_points_cad_local_m") or []
        tp = p.get("tool_path_parameters", {})
        welds[wname] = {"name": wname,
                        "seam_length_mm": round(sum(math.dist(a, b) for a, b in zip(pts, pts[1:])) * 1000, 3),
                        "binding": p["weld_library"].get("binding_mode"),
                        "positioner": tp.get("positioner_angles"),
                        "weave": None,
                        "weld_params": expected_params(p["weld_library"])}
        abb_weave = (p["weld_library"].get("weave_settings") or {}).get("abb") or {}
        if abb_weave.get("shape") in WEAVE_SHAPES and WEAVE_SHAPES[abb_weave["shape"]] > 0:
            # weavedata: shape, type, length, width, height, dwell left / center / right
            welds[wname]["weave"] = [WEAVE_SHAPES[abb_weave["shape"]], WEAVE_INTERPOLATIONS[abb_weave["interpolation"]]]                 + [float(abb_weave[k]) for k in ("length_mm", "width_mm", "height_mm", "dwell_left_mm",
                                                  "dwell_center_mm", "dwell_right_mm")]
        if not tp.get("weld_synchronous_motion") and literal and tp.get("positioner_part_transform_base"):
            welds[wname]["frame"] = base_weld_frame(tp["positioner_part_transform_base"], literal, touch.get(wid))
            welds[wname]["touch_up_mm"] = [round(touch[wid][i][3], 3) for i in range(3)] if wid in touch else None
    con.close()
    # Module order: the exporter marks each weld "! Start of <name>".
    order = re.findall(r"!\s*Start of (\S+)", text)
    mod_dir = os.path.join(out_dir, name + "_mod")
    os.makedirs(mod_dir, exist_ok=True)
    with open(os.path.join(mod_dir, os.path.basename(mod_path)), "w", encoding="utf-8", newline="") as fh:
        fh.write(text)
    expect = {"fixture": name, "covers": spec["covers"], "source": spec["source"],
              "module": os.path.basename(mod_path), "welds": [welds[w] for w in order]}
    if spec.get("station2_outcome"):
        # Station 2 must refuse it; the run expectations are for the other station.
        with open(os.path.join(out_dir, name + "_run_expect.json"), "w") as fh:
            json.dump(expect, fh, indent=1)
        with open(os.path.join(out_dir, name + "_expect.json"), "w") as fh:
            json.dump({"fixture": name, "covers": spec["covers"], "source": spec["source"],
                       "outcome": spec["station2_outcome"]}, fh, indent=1)
        return expect
    with open(os.path.join(out_dir, name + "_expect.json"), "w") as fh:
        json.dump(expect, fh, indent=1)
    return expect


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--expect-only", action="store_true",
                    help="rewrite the expected-values files of fixtures already built")
    args = ap.parse_args(argv)
    os.makedirs(args.out, exist_ok=True)
    failed = 0
    for name, spec in FIXTURES.items():
        if args.only and name not in args.only:
            continue
        dst = os.path.join(args.out, name + ".tgs")
        if spec.get("outcome"):
            if not args.expect_only:
                shutil.copyfile(spec["source"], dst)
                os.chmod(dst, 0o644)
                edit_project(dst, spec)
            with open(os.path.join(args.out, name + "_expect.json"), "w") as fh:
                json.dump({"fixture": name, "covers": spec["covers"], "source": spec["source"],
                           "outcome": spec["outcome"]}, fh, indent=1)
            print("%s: edited copy, expected outcome %s" % (name, spec["outcome"]))
            continue
        if args.expect_only:
            expect = write_expect(dst, name, spec, args.out)
            print("%s: expectations rewritten, %d weld(s)" % (name, len(expect["welds"])))
            continue
        shutil.copyfile(spec["source"], dst)
        os.chmod(dst, 0o644)
        edit_project(dst, spec)
        result = os.path.join(args.out, name + "_generate.json")
        # The planner's data root (config, weld library). A source run puts it next to the main
        # script, i.e. here; PLANNER_DATA holds a copy of the planner's weld library instead.
        env = dict(os.environ, TG_E2E_NAME_AFTER_PASSWORD="1", TG_E2E_PREPARE=json.dumps(spec.get("prepare", [])),
                   TGUIDE_DATA_DIR=PLANNER_DATA)
        subprocess.run([PYTHON, os.path.join(HERE, "planner_generate.py"), CUROBO, dst, result],
                       cwd=CUROBO, env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=1800)
        with open(result) as fh:
            gen = json.load(fh)
        if not (gen.get("generated") and gen.get("saved")):
            print("%s: planner did not generate and save: %s" % (name, gen.get("events")))
            failed += 1
            continue
        expect = write_expect(dst, name, spec, args.out)
        print("%s: generated in %s s, module %s, welds %s" % (
            name, gen.get("generate_s"), expect["module"],
            [(w["name"], w["seam_length_mm"], w["binding"], w["weld_params"]["travel_speed"]) for w in expect["welds"]]))
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
